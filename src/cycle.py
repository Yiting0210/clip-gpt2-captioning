"""Image -> caption -> image cycle: how much of the picture survives in the caption?

    python -m src.cycle --sources results/prefix_full_s0/beam_w3_test.json \
                                  results/baseline_blip2/blip2_test.json reference --n 100

Each caption source (a results JSON with a "captions" map, or "reference" = the first human caption)
is turned back into an image with Stable Diffusion v1.5. The regenerated image is compared with the
original by CLIP image-image cosine similarity (ViT-B/32 image embeddings, the same encoder the
captioners see). The same seed is used for one image across all sources, so the only thing that
changes between sources is the caption.

Outputs in results/cycle/:
  cycle.csv           one row per (image, source): caption, similarity, NSFW flag
  summary.json        mean similarity per source, with a 95% bootstrap interval
  <source>/<id>.jpg   the generated images (marked as AI-generated in every figure)
  cycle_gallery.png   original next to each source's regeneration, for a few images
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import torch

from src.data import IMG_DIR, PROC_DIR, load_captions, load_embeddings, load_splits
from src.evaluate import RESULTS, bootstrap_ci

SD_MODEL = "stable-diffusion-v1-5/stable-diffusion-v1-5"
OUT = RESULTS / "cycle"


def source_name(src: str) -> str:
    if src == "reference":
        return "reference"
    p = Path(src)
    return f"{p.parent.name}:{p.stem.removesuffix('_test').removesuffix('_val')}"


def load_source(src: str, ids, caps) -> dict[str, str]:
    if src == "reference":
        return {i: caps[i]["captions"][0] for i in ids}
    d = json.loads(Path(src).read_text(encoding="utf-8"))["captions"]
    missing = [i for i in ids if i not in d]
    if missing:
        raise ValueError(f"{src} lacks captions for {len(missing)} images, e.g. {missing[:3]}")
    return {i: d[i] for i in ids}


@torch.no_grad()
def image_embeddings(images, clip_model: str, device: str) -> torch.Tensor:
    from transformers import CLIPModel, CLIPProcessor
    model = CLIPModel.from_pretrained(clip_model).to(device).eval()
    proc = CLIPProcessor.from_pretrained(clip_model)
    out = []
    for s in range(0, len(images), 32):
        px = proc(images=images[s:s + 32], return_tensors="pt")["pixel_values"].to(device)
        out.append(torch.nn.functional.normalize(model.get_image_features(pixel_values=px).float(), dim=-1))
    return torch.cat(out).cpu()


def gallery(ids, names, caps, caption_sets, path: Path) -> Path:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import textwrap
    from PIL import Image

    cols = ["original"] + names
    fig, axes = plt.subplots(len(ids), len(cols), figsize=(2.6 * len(cols), 3.0 * len(ids)))
    for r, iid in enumerate(ids):
        for c, col in enumerate(cols):
            ax = axes[r, c]
            ax.axis("off")
            if col == "original":
                ax.imshow(Image.open(IMG_DIR / caps[iid]["file_name"]).convert("RGB"))
                ax.set_title("original photo", fontsize=8)
            else:
                ax.imshow(Image.open(OUT / col.replace(":", "__") / f"{iid}.jpg"))
                ax.set_title(textwrap.fill(f"[{col}] {caption_sets[col][iid]}", 34), fontsize=6.5)
    fig.suptitle("Columns after the first: images generated by Stable Diffusion v1.5 (AI-generated)", fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=100)
    plt.close(fig)
    return path


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--sources", nargs="+", required=True, help="results JSON files and/or 'reference'")
    p.add_argument("--n", type=int, default=100, help="test images (the first N of the test split)")
    p.add_argument("--steps", type=int, default=30)
    p.add_argument("--guidance", type=float, default=7.5)
    p.add_argument("--gallery", type=int, default=5)
    p.add_argument("--clip-model", default="openai/clip-vit-base-patch32")
    p.add_argument("--sd-model", default=SD_MODEL)
    a = p.parse_args()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    if device != "cuda":
        raise SystemExit("Stable Diffusion needs a GPU")
    from diffusers import StableDiffusionPipeline
    from PIL import Image

    caps, splits = load_captions(PROC_DIR), load_splits(PROC_DIR)
    ids = splits["test"][:a.n]
    names = [source_name(s) for s in a.sources]
    caption_sets = {n: load_source(s, ids, caps) for n, s in zip(names, a.sources)}

    pipe = StableDiffusionPipeline.from_pretrained(a.sd_model, torch_dtype=torch.float16).to(device)
    pipe.set_progress_bar_config(disable=True)
    generated: dict[str, dict[str, Image.Image]] = {n: {} for n in names}
    nsfw: dict[str, dict[str, bool]] = {n: {} for n in names}
    for name in names:
        d = OUT / name.replace(":", "__")
        d.mkdir(parents=True, exist_ok=True)
        for s in range(0, len(ids), 8):
            b = ids[s:s + 8]
            gens = [torch.Generator(device).manual_seed(int(i)) for i in b]   # same seed per image, every source
            out = pipe([caption_sets[name][i] for i in b], num_inference_steps=a.steps,
                       guidance_scale=a.guidance, generator=gens)
            flags = out.nsfw_content_detected or [False] * len(b)
            for i, im, f in zip(b, out.images, flags):
                im.save(d / f"{i}.jpg", quality=90)
                generated[name][i], nsfw[name][i] = im, bool(f)
        print(f"{name}: {len(ids)} images generated, {sum(nsfw[name].values())} flagged by the safety checker")
    del pipe
    torch.cuda.empty_cache()

    emb = load_embeddings(a.clip_model, PROC_DIR)
    orig = torch.nn.functional.normalize(torch.stack([emb["pooled"][emb["index"][i]] for i in ids]).float(), dim=-1)
    rows, summary = [], {}
    for name in names:
        g = image_embeddings([generated[name][i] for i in ids], a.clip_model, device)
        sim = (g * orig).sum(-1).tolist()
        ok = [s for s, i in zip(sim, ids) if not nsfw[name][i]]     # blacked-out images are excluded
        lo, hi = bootstrap_ci(ok)
        summary[name] = {"mean_similarity": round(sum(ok) / len(ok), 4), "lo": lo, "hi": hi,
                         "n": len(ok), "nsfw_flagged": len(ids) - len(ok)}
        rows += [{"image_id": i, "source": name, "caption": caption_sets[name][i], "similarity": round(s, 4),
                  "nsfw": nsfw[name][i]} for i, s in zip(ids, sim)]
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "cycle.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    meta = {"sd_model": a.sd_model, "steps": a.steps, "guidance": a.guidance, "n_images": len(ids),
            "similarity": "cosine of CLIP ViT-B/32 image embeddings, regenerated vs original"}
    (OUT / "summary.json").write_text(json.dumps({"settings": meta, "sources": summary}, indent=1), encoding="utf-8")
    print(json.dumps(summary, indent=1))
    if a.gallery:
        print("gallery:", gallery(ids[:a.gallery], names, caps, caption_sets, OUT / "cycle_gallery.png"))


if __name__ == "__main__":
    main()
